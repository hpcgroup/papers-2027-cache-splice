"""Writes data.csv for the model-validation figures: for every measured configuration of the attention-only model
(epoch time and peak memory), the prediction of the current white-box model (gt3d/dist/grid_select.py).  Run with the
gt3d Python environment (plexus_env); set GT3D to point to another checkout.

A configuration is named by the axes it splits (the classification of the paper's model section): "Ring" is the ring
layer on the (P, 1) grid, "Head" splits only the heads, (1, 1, P); otherwise 2D if it splits the columns (P_o > 1) and
1D if not (rows only, GP-AG), each "+ head" if it also uses the head axis (P_i > 1)."""
import csv
import os
import sys
from pathlib import Path

GT3D = Path(os.environ.get("GT3D", Path(__file__).resolve().parents[3] / "gt3d"))
sys.path.insert(0, str(GT3D))
from gt3d.dist import grid_select as gs  # noqa: E402
from bench.validate_model import graph  # noqa: E402
from dataclasses import replace  # noqa: E402
from bench.model_validation_data import HEADS, HEAD_MODEL, RING_MODEL, ONE_D_MODEL, ATTN_ONLY_LAYOUTS, HEADS8_MODEL, HEADS8_BSUB2  # noqa: E402

# attention-only model, LN, TF32, bf16 wire, pre-collective sync: HEAD_MODEL (2026-10-18, 4 / 16 / 64 GPUs), the 1D fused
# grids (P, 1) of ONE_D_MODEL and the ring layer of RING_MODEL (2026-10-23 / 10-26)
# DATA is keyed by (graph, hidden, heads): the tables above use HEADS[hidden] (128 -> 4 heads), and HEADS8_MODEL (2026-11-22)
# holds width 128 with 8 heads, which is what the paper shows since then (plot.py selects it by the heads column)
DATA = {k + (HEADS[k[1]],): {P: list(v) for P, v in byP.items()} for k, byP in HEAD_MODEL.items()}
for key, byP in ONE_D_MODEL.items():
    for P, pts in byP.items():
        DATA.setdefault(key + (HEADS[key[1]],), {}).setdefault(P, []).extend((P, 1, 1, "fused", ms, gb) for ms, gb in pts)
for key, byP in RING_MODEL.items():
    for P, pts in byP.items():
        DATA.setdefault(key + (HEADS[key[1]],), {}).setdefault(P, []).extend((P, 1, 1, "ring", ms, gb) for _, ms, gb in pts)
for key, byP in ATTN_ONLY_LAYOUTS.items():
    for P, pts in byP.items():
        DATA.setdefault(key + (HEADS[key[1]],), {}).setdefault(P, []).extend(pts)
for key, byP in HEADS8_MODEL.items():
    for P, pts in byP.items():
        DATA.setdefault(key, {}).setdefault(P, []).extend(pts)

rows = []
for (gname, hidden, heads), byP in DATA.items():
    g = graph(gname)
    m0 = gs.Model(hidden, heads, 4, True, with_gcn=False)
    for P, pts in byP.items():
        for pd, po, pi, layer, ms, peak in pts:
            # the 8-head runs chose --bwd_sub themselves (2 sub-blocks on some grids): the model gets the run's count
            two = heads == 8 and hidden == 128 and (pd, po, pi, layer) in HEADS8_BSUB2.get((gname, P), ())
            m = replace(m0, bwd_sub=2) if two else m0
            if layer == "ring":
                pr = gs.predict_ring_ms(pd, g, m)
                mem = gs.peak_memory_ring_bytes(pd, g.n, g.e_attn, hidden, g.f_in, 4, heads) / gs.GB
            elif layer == "head":
                pr = gs.predict_head_ms(pd, po, pi, g, m)
                mem = gs.peak_memory_head_bytes(pd, po, pi, g.n, g.e_attn, hidden, g.f_in, 4, heads,
                                                with_gcn=False, e_gcn=g.e_gcn) / gs.GB
            else:
                pr = gs.predict_fused_ms(pd, po, g, m)
                mem = gs.peak_memory_bytes(pd, po, g.n, g.e_attn, 0, hidden, g.f_in, 4, heads=heads) / gs.GB
            dim = ("Ring" if layer == "ring" else "Head" if pd == 1 and po == 1 and pi > 1
                   else ("2D" if po > 1 else "1D") + (" + head" if pi > 1 else ""))
            rows.append((gname, hidden, heads, P, dim, f"({pd},{po},{pi})", ms, round(pr, 2),
                         "" if peak is None else peak, round(mem, 3)))

out = Path(__file__).resolve().parent / "data.csv"
with open(out, "w", newline="") as f:
    f.write("# Generated by make_data.py: measured (gt3d bench/model_validation_data.py HEAD_MODEL, ONE_D_MODEL, RING_MODEL, ATTN_ONLY_LAYOUTS,\n"
            "# HEADS8_MODEL) vs the\n"
            "# white-box model (gt3d/dist/grid_select.py); attention-only Exphormer, ms per epoch and peak GB per GPU.\n"
            "# Empty measured_gb = activation-checkpointed run (excluded from the memory figure).\n")
    w = csv.writer(f)
    w.writerow(["graph", "hidden", "heads", "gpus", "dim", "grid", "measured_ms", "model_ms", "measured_gb", "model_gb"])
    w.writerows(rows)
print("wrote", out, len(rows), "rows")

# memory breakdown of the four layouts (ogbn-products, width 128, 4 heads) at 4 and 16 GPUs, next to the measured peak
g = graph("products")
BREAK = [(4, "1D", (4, 1, 1), "fused", 31.88), (4, "2D", (2, 2, 1), "fused", 26.06), (4, "3D", (1, 1, 4), "head", 20.65),
         (4, "Ring", (4, 1, 1), "ring", 15.55), (16, "1D", (16, 1, 1), "fused", 22.06), (16, "2D", (4, 4, 1), "fused", 10.46),
         (16, "3D", (2, 2, 4), "head", 6.10), (16, "Ring", (16, 1, 1), "ring", 4.01)]
out2 = Path(__file__).resolve().parent / "breakdown.csv"
with open(out2, "w", newline="") as f:
    f.write("# Generated by make_data.py: the memory model's terms (GB per GPU) for ogbn-products, width 128, 4 heads, attention-only;\n"
            "# measured_gb from HEAD_MODEL / ONE_D_MODEL / RING_MODEL.\n")
    w = csv.writer(f)
    w.writerow(["gpus", "layout", "grid", "base", "gathered", "owned", "transient", "model_gb", "measured_gb"])
    for P, dim, (pd, po, pi), layer, meas in BREAK:
        if layer == "ring":
            b = gs.peak_memory_ring_bytes(pd, g.n, g.e_attn, 128, g.f_in, 4, 4, breakdown=True)
        elif layer == "head":
            b = gs.peak_memory_head_bytes(pd, po, pi, g.n, g.e_attn, 128, g.f_in, 4, 4, with_gcn=False, e_gcn=g.e_gcn,
                                          breakdown=True)
        else:
            b = gs.peak_memory_bytes(pd, po, g.n, g.e_attn, 0, 128, g.f_in, 4, heads=4, breakdown=True)
        parts = [b[k] / gs.GB for k in ("base", "gathered", "owned", "transient")]
        w.writerow([P, dim, f"({pd},{po},{pi})"] + [round(x, 3) for x in parts] + [round(sum(parts), 3), meas])
print("wrote", out2)
